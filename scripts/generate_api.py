"""Generate checked-in API schema and frontend request types from Pydantic."""

import argparse
import json
import tomllib
from pathlib import Path

from marsd import __version__
from marsd.api import create_app
from marsd.contracts import Contract
from marsd.lineage import Declaration
from marsd.runs import Event, RunSpec

ROOT = Path(__file__).resolve().parents[1]


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(ts(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        return (
            f"Record<string, {ts(schema['additionalProperties'])}>"
            if isinstance(schema.get("additionalProperties"), dict)
            else "Record<string, unknown>"
        )
    return {
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "string": "string",
        "null": "null",
    }.get(kind, "unknown")


def generate():
    version = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["version"]
    versions = {
        "Python package": __version__,
        "frontend": json.loads((ROOT / "web/package.json").read_text())["version"],
        "npm lock": json.loads((ROOT / "web/package-lock.json").read_text())["version"],
        "npm root package": json.loads((ROOT / "web/package-lock.json").read_text())["packages"][
            ""
        ]["version"],
        "desktop": json.loads((ROOT / "desktop/src-tauri/tauri.conf.json").read_text())["version"],
        "Cargo": tomllib.loads((ROOT / "desktop/src-tauri/Cargo.toml").read_text())["package"][
            "version"
        ],
    }
    for name, value in versions.items():
        if value != version:
            raise SystemExit(
                f"Product version drift: {name} is {value}; pyproject.toml is {version}"
            )
    schema = create_app(".", launch_code="schema-generation-only", port=1).openapi()
    components = schema["components"]["schemas"]
    types = f"// Generated by scripts/generate_api.py; do not edit by hand.\nexport const VERSION = {json.dumps(version)};\n"
    for name in ("CSVPolicy", "Request"):
        model = components[name]
        types += f"export interface {name} {{\n"
        for field, definition in model["properties"].items():
            optional = "" if field in model.get("required", []) else "?"
            types += f"  {json.dumps(field)}{optional}: {ts(definition)};\n"
        types += "}\n"
    return {
        ROOT / "web/src/schema.ts": types,
        ROOT / "src/marsd/schemas/openapi.json": json.dumps(schema, indent=2) + "\n",
        ROOT / "src/marsd/schemas/contract.json": json.dumps(Contract.model_json_schema(), indent=2)
        + "\n",
        **{
            ROOT / f"src/marsd/schemas/{name}.json": json.dumps(model.model_json_schema(), indent=2)
            + "\n"
            for name, model in [("run", RunSpec), ("run-event", Event), ("lineage", Declaration)]
        },
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Generated API drift: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
