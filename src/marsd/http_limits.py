"""Bound streamed bodies before JSON parsing, including chunked requests."""

from typing import Any

from starlette.responses import JSONResponse

from marsd.domain import MarsdError


class BoundedBody:
    def __init__(self, app: Any, limit: int = 1024 * 1024):
        self.app, self.limit = app, limit

    async def __call__(self, scope: Any, receive: Any, send: Any) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return
        body = bytearray()
        while True:
            message = await receive()
            if message["type"] == "http.disconnect":
                return
            chunk = message.get("body", b"")
            if len(body) + len(chunk) > self.limit:
                response = JSONResponse(
                    {"error": MarsdError("BUDGET_EXCEEDED", "Request exceeds 1 MiB.").payload()},
                    status_code=413,
                )
                await response(scope, receive, send)
                return
            body.extend(chunk)
            if not message.get("more_body", False):
                break
        delivered = False

        async def replay() -> Any:
            nonlocal delivered
            if not delivered:
                delivered = True
                return {"type": "http.request", "body": bytes(body), "more_body": False}
            return await receive()

        await self.app(scope, replay, send)
